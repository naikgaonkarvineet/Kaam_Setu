export function translateText(value) {
  const text = value.trim()
  if (english[text]) return value.replace(text, english[text])
  if (text.endsWith('को आपका आवेदन पहुँचा')) return value.replace(text, `${text.replace('को आपका आवेदन पहुँचा', '')}: application received`)
  // Icon and separator text shares a node with copy (for example: "🧰 मैं ठेकेदार हूँ").
  // Replace the longest phrases first so complete labels win over individual words.
  const protectedBrand = value.replaceAll('कामसेतु', '__KAAMSETU__')
  return Object.entries(english)
    .sort(([a], [b]) => b.length - a.length)
    .reduce((translated, [hindi, englishText]) => translated.replaceAll(hindi, englishText), protectedBrand)
    .replaceAll('__KAAMSETU__', 'कामसेतु')
}
